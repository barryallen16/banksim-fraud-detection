# 3. Enhanced Cluster Processing (Fixed)
def process_clusters(dbscan, data, true_labels, params):
    """Complete cluster processing pipeline with proper type handling"""
    labels = dbscan.fit_predict(data)

    # Convert to numpy array if needed
    if hasattr(labels, 'get'):
        labels_np = labels.get()
    else:
        labels_np = cp.asnumpy(labels) if cp.is_cupy(labels) else labels

    # Count clusters (excluding noise)
    unique_clusters = np.unique(labels_np)
    n_clusters = len(unique_clusters) - (1 if -1 in unique_clusters else 0)

    if n_clusters < 1:
        return None

    # Convert true_labels to numpy and cast to int32
    y_true = true_labels.to_numpy(dtype=np.int32) if hasattr(true_labels, 'to_numpy') else true_labels.astype(np.int32)

    # Dynamic labeling
    pred_labels = np.zeros(len(labels_np), dtype=np.int32) # Cast pred_labels to int32
    for cluster in unique_clusters:
        if cluster == -1:
            continue

        mask = labels_np == cluster
        size = mask.sum()
        if size < 5:  # Skip small clusters
            continue

        fraud_ratio = y_true[mask].mean()
        if fraud_ratio > params['fraud_threshold']:
            pred_labels[mask] = 1

    return pred_labels

# 4. Main Execution
best_metrics = {'f1': -1, 'precision': 0, 'recall': 0}
