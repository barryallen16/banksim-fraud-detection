# 1. Robust EPS Calculation (Fixed)
def calculate_optimal_eps(data, k=5):
    """More reliable EPS calculation with validation"""
    data_np = data.get() if hasattr(data, 'get') else cp.asnumpy(data)
    knn = NearestNeighbors(n_neighbors=k).fit(data_np)
    distances, _ = knn.kneighbors()
    k_dist = np.sort(distances[:, -1])

    # Find "elbow" point using angle method
    x_range = len(k_dist)
    y_range = k_dist[-1] - k_dist[0]
    angles = np.arctan2(k_dist - k_dist[0], np.arange(len(k_dist)))
    elbow = np.argmax(angles)

    eps = k_dist[elbow] * 1.2  # Conservative multiplier
    return max(eps, 0.15)  # Ensure reasonable minimum EPS

